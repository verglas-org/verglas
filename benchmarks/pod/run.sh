#!/usr/bin/env bash
# TPC-H constrained PROFILE on a multi-node dev pod (issues #160, #29, #141).
#
# The single-node "constrained" profile (benchmarks/tpch) sizes one daemon's
# disk to ~50% of the SF1 footprint and measures eviction pressure. This pod
# profile runs the SAME three legs through NODE 0 of an N-node `verglas dev` pod
# where EACH node carries the constrained per-node budget — so the pod's
# aggregate cache is N x per-node. With rendezvous ownership (#28) a single
# client through node 0 fans reads across owners: locally-owned blocks fill from
# the backend, cross-owner blocks are served by PEER FETCH (#29). The evidence
# that the pod behaves as one cache is per-node /admin/stats, not latency:
# node 0's peer_hits > 0 (it read cross-owner blocks off-node) and the owners'
# peer_served_blocks > 0 (they served them). This script boots the pod on
# uncontended ports, runs the legs, and prints that per-node evidence.
#
# Reuses benchmarks/tpch/tpch_bench.py as the driver and benchmarks/tpch's
# pinned venv. Nothing here runs in CI. See README.md for every input.
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TPCH="$HERE/../tpch"
DRIVER="$TPCH/tpch_bench.py"
VENV="$TPCH/.venv"
STATS="$HERE/pod_stats.py"

# ---- defaults (override via flags or env) --------------------------------- #
NODES="${POD_NODES:-3}"
DRAM="${POD_DRAM:-80MB}"                       # per node
CACHE_SIZE="${POD_CACHE_SIZE:-122MB}"          # per node (~50% of SF1 footprint)
ADMIT_PROB="${POD_ADMIT_PROBABILITY:-}"        # optional --admit-probability P
BASE_PORT="${POD_BASE_PORT:-18400}"            # base; each node takes a 4-port block
SCALE="${POD_SCALE:-1}"
BUCKET="${POD_BUCKET:-hyperglas}"
PREFIX="${POD_PREFIX:-}"                        # resolved once SCALE is known
NAMESPACE="${POD_NAMESPACE:-tpch}"
CATALOG_DB="${POD_CATALOG_DB:-$HERE/catalog.db}"
READ_MODE="${POD_READ_MODE:-auto}"
CACHE_NOTE="${POD_CACHE_NOTE:-pod constrained per node (medium unspecified)}"
OUT_DIR="${POD_OUT_DIR:-$HERE/out}"
PHASE="all"                                    # all | seed | query | teardown

usage() {
  cat <<'EOF'
Usage: run.sh [options]

Phases (default: all = seed then query, both against a freshly booted pod):
  --seed-only        boot the pod, write the Iceberg tables through node 0, tear down
  --query-only       boot the pod, run the 22 queries x three legs + per-node stats
  --teardown         delete the prefix and the SQLite catalog (no pod needed)

Pod shape:
  --nodes N          nodes in the pod (default 3)
  --dram SIZE        per-node DRAM ceiling (default 80MB, the engine floor)
  --cache-size SIZE  per-node disk ceiling (default 122MB ~= 50% of SF1 footprint)
  --admit-probability P   resident-biased admission fraction per node (#164; default off)
  --base-port P      base port; node i takes ports P+i*4 .. P+i*4+3 (default 18400)

Dataset / driver:
  --scale N          TPC-H scale factor (default 1)
  --bucket NAME      origin bucket (default hyperglas)
  --prefix PATH      table prefix (default bench/pod-sf<SCALE>); never the bucket root
  --catalog-db PATH  SQLite catalog file (default ./catalog.db)
  --read-mode MODE   auto | duckdb-iceberg | pyiceberg-arrow (default auto)
  --cache-note TEXT  cache-medium disclosure for the report
  --out-dir DIR      where per-run JSON + stats snapshots are written (default ./out)

Origin creds come from the ambient AWS_* environment (load your .env first:
  set -a; source .env; set +a). Dev keys are generated by the pod and parsed
from its banner automatically.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --seed-only)   PHASE="seed"; shift ;;
    --query-only)  PHASE="query"; shift ;;
    --teardown)    PHASE="teardown"; shift ;;
    --nodes)       NODES="$2"; shift 2 ;;
    --dram)        DRAM="$2"; shift 2 ;;
    --cache-size)  CACHE_SIZE="$2"; shift 2 ;;
    --admit-probability) ADMIT_PROB="$2"; shift 2 ;;
    --base-port)   BASE_PORT="$2"; shift 2 ;;
    --scale)       SCALE="$2"; shift 2 ;;
    --bucket)      BUCKET="$2"; shift 2 ;;
    --prefix)      PREFIX="$2"; shift 2 ;;
    --catalog-db)  CATALOG_DB="$2"; shift 2 ;;
    --read-mode)   READ_MODE="$2"; shift 2 ;;
    --cache-note)  CACHE_NOTE="$2"; shift 2 ;;
    --out-dir)     OUT_DIR="$2"; shift 2 ;;
    -h|--help)     usage; exit 0 ;;
    *) echo "unknown flag: $1" >&2; usage; exit 2 ;;
  esac
done

if [[ -z "$PREFIX" ]]; then PREFIX="bench/pod-sf${SCALE}"; fi
if [[ -z "$(printf '%s' "$PREFIX" | tr -d '/')" ]]; then
  echo "error: --prefix must be non-empty (never the bucket root)" >&2; exit 2
fi

# ---- locate the verglas binaries (built once: cargo build --release) ------ #
BIN=""
for cand in "$HERE/../../target/release" "$HERE/../../target/debug"; do
  if [[ -x "$cand/verglas" && -x "$cand/verglasd" ]]; then BIN="$cand"; break; fi
done
if [[ -z "$BIN" ]]; then
  echo "error: verglas/verglasd not found under target/{release,debug}." >&2
  echo "       Build them once: cargo build --release" >&2
  exit 2
fi

# ---- idempotent venv (shared with benchmarks/tpch) ------------------------ #
if [[ ! -x "$VENV/bin/python" ]]; then
  echo "[setup] creating venv at $VENV" >&2
  PYBIN="$(command -v python3.13 || command -v python3)"
  "$PYBIN" -m venv "$VENV"
fi
STAMP="$VENV/.requirements.sha"; REQ="$TPCH/requirements.txt"
NEWSHA="$(shasum "$REQ" | awk '{print $1}')"
if [[ ! -f "$STAMP" || "$(cat "$STAMP")" != "$NEWSHA" ]]; then
  echo "[setup] installing pinned dependencies" >&2
  "$VENV/bin/pip" install -q --upgrade pip
  "$VENV/bin/pip" install -q -r "$REQ"
  echo "$NEWSHA" > "$STAMP"
fi
PY="$VENV/bin/python"

need_origin_keys() {
  if [[ -z "${AWS_ACCESS_KEY_ID:-}" || -z "${AWS_ENDPOINT:-}" ]]; then
    echo "error: origin creds required in the environment (AWS_ENDPOINT," >&2
    echo "       AWS_ACCESS_KEY_ID, AWS_SECRET_ACCESS_KEY, AWS_REGION)." >&2
    echo "       Load your .env first: set -a; source .env; set +a" >&2
    exit 2
  fi
}

# ---- teardown-only short-circuit (no pod needed) -------------------------- #
if [[ "$PHASE" == "teardown" ]]; then
  need_origin_keys
  "$PY" "$DRIVER" teardown --scale "$SCALE" --bucket "$BUCKET" --prefix "$PREFIX" \
    --namespace "$NAMESPACE" --catalog-db "$CATALOG_DB" \
    --verglas-endpoint "http://127.0.0.1:$BASE_PORT" \
    --verglas-access-key-id x --verglas-secret-access-key x --verglas-region us-east-1
  exit $?
fi

need_origin_keys
mkdir -p "$OUT_DIR"

# ---- uncontended ports (guards the #194 probe-then-bind TOCTOU) ----------- #
# The pod uses ports BASE .. BASE + NODES*4 - 1. Scan upward for a block where
# every port is free right now (lsof), then hand that base to `verglas dev`.
ports_free() { # $1=base
  local b="$1" i p
  for ((i=0; i<NODES*4; i++)); do
    p=$((b+i))
    if lsof -nP -iTCP:"$p" -sTCP:LISTEN >/dev/null 2>&1; then return 1; fi
  done
  return 0
}
PORT="$BASE_PORT"
for _ in $(seq 1 50); do
  if ports_free "$PORT"; then break; fi
  echo "[ports] base $PORT block busy; trying $((PORT+ NODES*4))" >&2
  PORT=$((PORT + NODES*4))
done
if ! ports_free "$PORT"; then echo "error: no free port block from $BASE_PORT" >&2; exit 2; fi

# Admin URLs for every node, derived from the pod's port layout (S3=base+i*4,
# admin=base+i*4+1) — the same layout bins/verglas/src/commands/dev.rs plans.
ADMINS=(); LABELS=""
for ((i=0; i<NODES; i++)); do
  a=$((PORT + i*4 + 1))
  ADMINS+=("http://127.0.0.1:$a")
  LABELS="${LABELS:+$LABELS,}node-$i"
done
NODE0_S3="http://127.0.0.1:$PORT"
NODE0_ADMIN="http://127.0.0.1:$((PORT+1))"

wait_ready() { # $1=admin-port
  for _ in $(seq 1 150); do
    curl -sf "http://127.0.0.1:$1/admin/healthz" >/dev/null 2>&1 && return 0; sleep 0.2
  done
  return 1
}

# ---- boot the pod (background); teardown by launcher pid on exit ---------- #
POD_CACHE="$(mktemp -d "${TMPDIR:-/tmp}/verglas-pod-XXXXXX")"
POD_LOG="$OUT_DIR/pod-daemon.log"
# The ${arr[@]+...} guard keeps an EMPTY array from tripping `set -u` under
# macOS's stock bash 3.2 (empty arrays count as unset there).
ADMIT_FLAG=(); [[ -n "$ADMIT_PROB" ]] && ADMIT_FLAG=(--admit-probability "$ADMIT_PROB")
echo "[pod] booting $NODES nodes at base $PORT (dram=$DRAM disk=$CACHE_SIZE per node${ADMIT_PROB:+, admit-probability=$ADMIT_PROB})" >&2
"$BIN/verglas" dev --nodes "$NODES" --port "$PORT" --dram "$DRAM" --cache-size "$CACHE_SIZE" \
  ${ADMIT_FLAG[@]+"${ADMIT_FLAG[@]}"} --cache-dir "$POD_CACHE" > "$POD_LOG" 2>&1 &
LAUNCHER=$!

teardown_pod() {
  kill "$LAUNCHER" 2>/dev/null
  # The #170 parent-death watch reaps the verglasd children; wait for node 0's
  # admin to stop answering, then remove the ephemeral pod cache.
  for _ in $(seq 1 50); do curl -sf "$NODE0_ADMIN/admin/healthz" >/dev/null 2>&1 || break; sleep 0.2; done
  rm -rf "$POD_CACHE"
}
trap teardown_pod EXIT

for ((i=0; i<NODES; i++)); do
  if ! wait_ready $((PORT + i*4 + 1)); then
    echo "[pod] node $i failed to become ready" >&2; cat "$POD_LOG" >&2; exit 1
  fi
done

# Wait for GOSSIP CONVERGENCE (#27): every node must see all N members before any
# read, or node 0's ring owns every key and there is no peer routing to observe.
echo "[pod] waiting for gossip to converge on $NODES members …" >&2
converged=0
for _ in $(seq 1 150); do
  seen=$(curl -s "$NODE0_ADMIN/admin/members" 2>/dev/null \
    | "$VENV/bin/python" -c "import sys,json;print(len(json.load(sys.stdin).get('members',[])))" 2>/dev/null || echo 0)
  if [[ "$seen" == "$NODES" ]]; then converged=1; break; fi
  sleep 0.2
done
if [[ "$converged" != 1 ]]; then echo "[pod] gossip did not converge on $NODES members" >&2; exit 1; fi

KEY=$(grep -m1 -oE 'access_key_id=VG[0-9A-F]+' "$POD_LOG" | cut -d= -f2)
SEC=$(grep -m1 -oE 'secret_access_key=[0-9a-f]+' "$POD_LOG" | cut -d= -f2)
echo "[pod] ready + converged: node0 $NODE0_S3 (dev key $KEY); admins: ${ADMINS[*]}" >&2

common=(--scale "$SCALE" --bucket "$BUCKET" --prefix "$PREFIX" --namespace "$NAMESPACE"
        --catalog-db "$CATALOG_DB" --verglas-endpoint "$NODE0_S3"
        --verglas-access-key-id "$KEY" --verglas-secret-access-key "$SEC"
        --verglas-region us-east-1)

if [[ "$PHASE" == "seed" ]]; then
  "$PY" "$DRIVER" generate "${common[@]}"
  exit $?
fi

# ---- query phase: snapshot every node, run the legs, snapshot again ------- #
BEFORE="$OUT_DIR/stats-before.json"; AFTER="$OUT_DIR/stats-after.json"
SNAP_ARGS=(); for a in "${ADMINS[@]}"; do SNAP_ARGS+=(--admin "$a"); done
"$PY" "$STATS" snapshot --out "$BEFORE" "${SNAP_ARGS[@]}"

"$PY" "$DRIVER" query "${common[@]}" --read-mode "$READ_MODE" \
  --cache-note "$CACHE_NOTE" --profile pod-constrained \
  --admin-endpoint "$NODE0_ADMIN" --json > "$OUT_DIR/query.json" 2> "$OUT_DIR/query.stderr"
QRC=$?

"$PY" "$STATS" snapshot --out "$AFTER" "${SNAP_ARGS[@]}"

echo
echo "=== pod query report (node 0 legs, from tpch driver) ==="
"$PY" - "$OUT_DIR/query.json" <<'PYEOF'
import json, sys
# The driver prints progress lines to stdout before the JSON blob; parse from
# the first '{'.
txt = open(sys.argv[1]).read()
r = json.loads(txt[txt.index("{"):])
t = r.get("totals", {})
print(f"  profile: {r['machine'].get('profile')}  read_mode: {r.get('read_mode')}")
print(f"  totals ms: direct={t.get('direct_ms')} cold={t.get('cold_ms')} warm={t.get('warm_ms')} "
      f"direct/warm={t.get('speedup_direct_over_warm')}")
cs = r.get("cache_stats", {})
if cs.get("available"):
    d = cs.get("warm_leg_counter_delta", {})
    print(f"  node-0 warm-leg delta: dram_hits={d.get('dram_hits')} disk_hits={d.get('disk_hits')} "
          f"peer_hits={d.get('peer_hits')} backend_fills={d.get('backend_fills')}")
PYEOF

echo
echo "=== PART 1 — fresh-pod node-0 ingress: per-node /admin/stats deltas ==="
echo "(whole query phase: direct+cold+warm through node 0 on a cold pod)"
"$PY" "$STATS" report --before "$BEFORE" --after "$AFTER" --labels "$LABELS" | tee "$OUT_DIR/evidence-part1.txt"

# ---- PART 2 — pod-coherence demo (does the pod act as ONE cache?) ---------- #
# Peer serving is cache-only (#29): an owner serves a peer a block only if it is
# already resident on that owner, and warm-from-peers (#30) is unmerged — so a
# node caches an owned block only when it is DIRECTLY hit for it. With node-0-only
# ingress the owners never self-warm, so Part 1 shows peer-fetch ATTEMPTS
# (peer_misses) but few peer_hits. This part reproduces the realistic distributed
# pod: first warm every node's owned share (a sweep of the SF1 objects through
# EACH node, so every owner gets a direct hit for the keys it owns), then read the
# whole dataset back through node 0. Cross-owner reads are now served by peers
# (peer_hits on node 0, peer_served_blocks on the owners) and the pod's aggregate
# disk (N x per-node) holds the whole footprint — so the read sweep's aggregate
# backend_fills collapse: the pod behaving as one cache.
if command -v aws >/dev/null 2>&1; then
  OBJS="$OUT_DIR/objects.txt"
  AWS_ACCESS_KEY_ID="$KEY" AWS_SECRET_ACCESS_KEY="$SEC" AWS_REGION=us-east-1 \
    aws --endpoint-url "$NODE0_S3" s3 ls --recursive "s3://$BUCKET/$PREFIX/" 2>/dev/null \
    | awk '{print $4}' | grep -v '^$' > "$OBJS" || true
  nobj=$(wc -l < "$OBJS" | tr -d ' ')
  if [[ "$nobj" -gt 0 ]]; then
    sweep() { # $1=s3-port
      while read -r o; do [[ -z "$o" ]] && continue
        AWS_ACCESS_KEY_ID="$KEY" AWS_SECRET_ACCESS_KEY="$SEC" AWS_REGION=us-east-1 \
          aws --endpoint-url "http://127.0.0.1:$1" s3 cp "s3://$BUCKET/$o" /dev/null >/dev/null 2>&1
      done < "$OBJS"; }
    echo
    echo "[coherence] warming every owner: sweeping $nobj objects through each of $NODES nodes …" >&2
    for ((i=0; i<NODES; i++)); do sweep $((PORT + i*4)); done
    CBEFORE="$OUT_DIR/coherence-before.json"; CAFTER="$OUT_DIR/coherence-after.json"
    "$PY" "$STATS" snapshot --out "$CBEFORE" "${SNAP_ARGS[@]}"
    echo "[coherence] reading all $nobj objects back through node 0 …" >&2
    sweep "$PORT"
    "$PY" "$STATS" snapshot --out "$CAFTER" "${SNAP_ARGS[@]}"
    echo
    echo "=== PART 2 — pod-coherence: read the whole dataset through node 0 (owners warm) ==="
    echo "(this delta is ONE read sweep of every object through node 0; the pod already"
    echo " holds the footprint across owners, so cross-owner reads are peer_hits and the"
    echo " aggregate backend_fills show how little the backend is touched)"
    "$PY" "$STATS" report --before "$CBEFORE" --after "$CAFTER" --labels "$LABELS" | tee "$OUT_DIR/evidence-part2.txt"
  else
    echo "[coherence] no objects listed under $PREFIX; skipping Part 2" >&2
  fi
else
  echo "[coherence] aws CLI not found; skipping Part 2 (install awscli to run the coherence demo)" >&2
fi

exit $QRC
